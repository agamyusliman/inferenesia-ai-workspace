/** Only tight chrome labels forced to English in every locale. */
export const ACTION_MESSAGE_KEYS: MessageKey[] = [
  'action.save',
  'action.undo',
  'action.redo',
  'action.close',
  'action.cancel',
  'action.copy',
  'action.send',
  'action.stop',
]

const ACTION_KEY_SET = new Set<string>(ACTION_MESSAGE_KEYS)

export function isActionKey(key: MessageKey): boolean {
  return ACTION_KEY_SET.has(key)
}

export function catalogFor(locale: 'en' | 'id'): Record<MessageKey, string> {
  return locale === 'id' ? id : (en as Record<MessageKey, string>)
}
